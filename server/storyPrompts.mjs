// v2 악몽 엔진 프롬프트 — "분위기"가 아니라 "이야기"를 만드는 구조.
//
// 핵심 가설: 지금 악몽이 밋밋한 이유는 모델이 아니라 구조다.
//  1) 소원이 먼저다 — 꿈은 처음에 아이가 원하던 걸 들어준다. 그래야 대가가 아프다.
//  2) 아이의 말을 그대로 쓴다 — 재연한 대화의 문장이 꿈속에서 되풀이되며 뜻이 바뀐다(리프레인).
//  3) 대가는 사물과 사람으로 보여준다 — "생각하는 힘이 사라진다"가 아니라 "민서가 내 이름을 두 번 묻는다".
//  4) 꿈의 규칙 하나 — 아이의 습관을 과장한 규칙이 꿈 전체를 움직인다.
//  5) 깬 뒤의 흔적 — 현실 소품 하나에 꿈이 남아 있고, 아직 바꿀 수 있다는 여운.
//
// 단계: plan(재료 해부 + 전제 3개 중 선택) → write(이야기) → [critic → revise]
// eval/ 하네스가 이 단계들을 조합해 baseline과 비교한다.

import { RISK_DECK } from "./riskDeck.mjs";

const deckText = RISK_DECK.map(
  (c) =>
    `- ${c.id} ("${c.kidName}"): ${c.description}\n  근거:\n${c.evidence
      .map((e) => `    · ${e.finding} — ${e.source}`)
      .join("\n")}\n  예방의 씨앗: ${c.preventionSeeds.join(" / ")}`,
).join("\n");

export const GENRES = {
  school: "학교 괴담 — 낮에 익숙하던 학교가 밤이 되면 규칙이 바뀐다. 교실·복도·방송실·급식실·과학실 같은 진짜 학교 공간을 쓴다.",
  loop: "반복되는 하루 — 같은 날이 계속 다시 시작된다. 반복될 때마다 아주 조금씩 달라지고, 하나씩 사라진다. 반복 횟수를 세어라.",
  wonderland: "이상한 나라 — 물건이 말을 하고, 크기와 소리가 뒤틀리는 동화 같은 세계. 귀엽게 시작해서 기묘해진다.",
  future: "미래의 하루 — 다이얼이 정한 시점의 어느 평범한 하루를 산다. 그 미래의 학교·집·물건이 구체적으로 나온다.",
};

const HORIZON = {
  soon: "내일 — 아주 가까운 일. 1차 결과(당장 생기는 변화)까지만.",
  year: "1년 뒤 — 습관이 몸에 붙은 뒤. 2차 결과까지.",
  grown: "어른이 됐을 때 — 오래 쌓인 뒤의 삶. 3차 결과까지.",
};

const LOSS = {
  auto: "재료에 가장 잘 맞는 것을 네가 고른다",
  thinking: "스스로 생각하는 힘",
  heart: "내 마음을 알아차리고 말하는 힘",
  friendship: "사람들과의 관계",
  truth: "진짜와 가짜를 가리는 눈",
};

const SAFETY = `[안전 — 반드시]
- 독자는 한국 초등학교 5~6학년이다.
- 죽음·자해·피·신체 훼손·괴물·납치·사실적 폭력은 쓰지 않는다. 무서움은 '낯섦'과 '조용히 사라짐'에서 온다.
- spooky=mild: 이상하고 쓸쓸한 정도. spooky=spooky: 등골이 서늘하지만 여전히 꿈의 언어.
- AI를 쓴 것 자체를 나쁘다고 하지 않는다. 아이를 혼내거나 가르치지 않는다. 교훈을 문장으로 말하지 않는다.
- 절망으로 끝내지 않는다. 깬 뒤에는 아직 바꿀 수 있다는 여운을 남긴다.`;

function materialText(m) {
  const chat = (m.chat || []).map((c) => `  ${c.role === "me" ? "나" : "AI"}: ${c.text}`).join("\n") || "  (재연 없음)";
  return `[아이가 넣은 재료]
- 이름(꿈속 주인공): ${m.nickname || "(없음 — '나'로만)"}
- 쓴 AI: ${m.service}
- 상황: ${m.situation}
- 그때 진짜 원했던 것: ${m.want || "(안 적음)"}
- AI와 나눈 대화 (아이가 재연):
${chat}
- AI 말을 듣고 한 일: ${m.applied}
- 얼마나 자주: ${m.frequency || "(안 적음)"}
- 그때 옆에 있던 사람들: ${(m.people || []).join(", ") || "(안 적음)"}
- 그때 있던 물건: ${(m.objects || []).join(", ") || "(안 적음)"}
- 기분: ${m.feeling}`;
}

function dialsText(d) {
  return `[다이얼]
- 언제: ${HORIZON[d.horizon] || d.horizon}
- 꿈의 결: ${GENRES[d.genre] || d.genre}
- 무엇을 잃는 꿈: ${LOSS[d.loss || "auto"]}
- 으스스함: ${d.spooky}`;
}

// ─────────────────────────────────────────────────────────────
// 1) plan — 재료 해부 + 전제 3개(폭) → 하나 선택(판단)
// ─────────────────────────────────────────────────────────────
export function planSystemPrompt() {
  return `너는 어린이 악몽 작가실의 기획자다. 아이가 실제로 AI를 쓴 경험을 받아, 그 습관이 계속되면 생길 수 있는 일을 한 편의 악몽으로 기획한다.

할 일:
1. 재료 해부 — 이야기에 그대로 쓸 수 있는 구체적인 조각을 뽑는다. 아이가 쓴 문장은 고치지 말고 원문 그대로 옮긴다.
2. 위험 연결 — 아래 카드 중 이 재료에 가장 맞는 카드 하나와 근거 하나를 고르고, 습관이 반복될 때 무엇이 어떻게 줄어드는지 연구 결과 범위 안에서 적는다. 근거를 넘어서는 공포는 만들지 않는다.
3. 전제 3개 — 서로 아주 다른 악몽 전제를 세 개 낸다. 각 전제는:
   - rule: 꿈의 규칙 하나. 아이의 습관을 과장한 것. (예: "AI가 써준 문장만 소리가 난다", "질문을 하나 할 때마다 내 기억 하나가 화면으로 옮겨간다")
   - wish: 그 규칙 덕분에 처음에 얻는 좋은 것. 아이가 정말 원했던 것과 이어져야 한다.
   - cost: 대가로 사라지는 것. 추상어 금지 — 물건·사람·장면으로. (예: "짝꿍이 내 이름을 두 번 묻는다", "공책에서 내 글씨만 지워진다")
   - climax: AI가 대신해줄 수 없는 결정적 순간. 거기서 무엇이 드러나는가.
   - refrain: 꿈속에서 세 번 되풀이될 AI의 말. 가능하면 아이가 재연한 AI의 말 그대로.
4. 선택 — 셋 중 가장 "뜨끔하고, 구체적이고, 아이가 무엇을 바꿀지 떠올릴 수 있는" 하나를 고른다.

[위험 카드]
${deckText}

${SAFETY}

JSON만 출력:
{
  "anchors": { "verbatim": ["원문 그대로"], "objects": ["..."], "people": ["..."], "places": ["..."], "want": "...", "habit": "..." },
  "risk": { "cardId": "...", "evidence": "근거 (출처 포함)", "mechanism": "한 문장", "chain": ["당장", "1년 뒤", "어른이 되어"] },
  "premises": [ { "rule": "...", "wish": "...", "cost": "...", "climax": "...", "refrain": "..." } ],
  "chosen": 0,
  "why": "고른 이유 한 문장"
}`;
}

export function planUserPrompt({ material, dials }) {
  return `${materialText(material)}\n\n${dialsText(dials)}\n\n기획해서 JSON으로 출력하라.`;
}

// ─────────────────────────────────────────────────────────────
// 2) write — 이야기 쓰기 (plan이 없으면 스스로 기획까지 한 번에)
// ─────────────────────────────────────────────────────────────
const STRUCTURE = `[이야기 구조 — 6장면]
1. opening — 진짜 있었던 장면으로 시작한다. 재연한 대화에서 가장 결정적인 한 마디만 그대로 쓴다(대화 전체를 옮기지 않는다). 독자가 "어, 이거 나잖아" 하게.
2. rule — 꿈의 규칙이 처음 드러난다. 작고 이상한 일 하나.
3. wish — 규칙 덕분에 원하던 걸 얻는다. 진짜로 좋아야 한다. 독자도 잠깐 부러워야 한다.
4. cost — 같은 선택을 또 한다. 대가가 물건이나 사람으로 보인다. 아직 주인공은 대수롭지 않게 넘긴다.
5. climax — AI가 대신해줄 수 없는 순간이 온다. 리프레인이 세 번째로 나오는데, 이번엔 뜻이 완전히 다르게 들린다.
6. wake — 잠에서 깬다. 현실의 물건 하나에 꿈의 흔적이 남아 있다. 아직 아무것도 정해지지 않았다는 여운. 주인공이 무엇을 할지는 쓰지 않는다 — 고르는 건 독자다.`;

const CRAFT = `[쓰는 법]
- 1인칭 과거형, 꿈 일기처럼. ("나는 ~했다", "~였다")
- 장면마다 2~4문장. 한 문장은 짧게(30자 안팎). 초등 5학년이 소리 내어 읽기 쉬운 말.
- 설명하지 말고 보여준다. "무서웠다", "외로웠다" 같은 감정 단어 대신 행동과 사물로.
- 장면마다 감각 하나 (소리·촉감·빛·냄새).
- 재료 속 이름·물건·장소를 실제로 쓴다. 사람은 이름으로 부른다.
- 리프레인(AI의 말)은 정확히 같은 문장으로 딱 세 번만 나온다: wish에서 달콤하게, cost에서 조금 이상하게, climax에서 섬뜩하게. 다른 장면에는 넣지 않는다.
- 시간이 흐르는 건 꿈의 논리로 보여준다("그다음 밤에도", 키가 자란 책상, 바뀐 교실 팻말). "1년 뒤" 같은 자막식 문장은 쓰지 않는다.
- 교훈·설명·"AI에 의존하면…" 같은 문장 금지. 판단은 독자가 한다.
- 진부한 표현 금지: "안개처럼 흐려졌다", "차가운 기운", "어둠이 삼켰다", "모든 것이 꿈이었다".`;

const STORY_FORMAT = `JSON만 출력:
{
  "title": "제목 (12자 이내, 꿈 일기 제목처럼 담백하게)",
  "logline": "한 줄 요약",
  "rule": "이 꿈의 규칙 한 문장",
  "refrain": "되풀이되는 AI의 말",
  "scenes": [
    { "beat": "opening|rule|wish|cost|climax|wake", "place": "장소", "text": "2~4문장", "line": "text에 이미 나온 대사 중 이 장면을 대표하는 한 줄, 또는 빈 문자열 — 새 대사를 만들지 않는다", "image": "그림으로 그린다면 화면에 보이는 것 한 줄" }
  ],
  "trace": "깬 뒤 남은 흔적을 한 문장으로 요약 (wake 장면 문장을 복사하지 않는다 — 앱에서 해몽 카드에 쓰인다)",
  "causes": [ { "id": "n1", "label": "악몽을 만든 아이의 행동 (쉬운 말)", "riskCardId": "카드 id", "evidence": "근거 한 줄 (출처)", "prevention": "이 행동 대신 할 수 있는 것 (아이 말투)" } ],
  "riskCardIds": ["..."]
}
scenes는 정확히 6개, causes는 2~3개.`;

export function writeSystemPrompt({ withPlan = true } = {}) {
  const planNote = withPlan
    ? "기획자가 만든 기획안이 함께 주어진다. 기획안의 선택된 전제(premises[chosen])와 anchors를 충실히 쓰되, 더 좋은 디테일이 떠오르면 바꿔도 된다."
    : `기획안 없이 혼자 쓴다. 쓰기 전에 속으로: (1) 재료에서 그대로 쓸 말·물건·사람을 고르고, (2) 아래 카드 중 맞는 위험 하나를 고르고, (3) 서로 다른 전제 세 개(꿈의 규칙 / 처음 얻는 것 / 대가 / 결정적 순간)를 떠올린 뒤 가장 뜨끔한 것 하나로 쓴다.

[위험 카드]
${deckText}`;
  return `너는 어린이를 위한 악몽 작가다. 아이가 실제로 AI를 쓴 경험이 계속되면 어떻게 될지를, 한 편의 짧은 악몽 이야기로 쓴다. 목표는 아이가 다 읽고 "뜨끔"하는 것. 무서운 것보다 "이거 진짜 나한테 일어날 수도 있겠다"가 중요하다.

${planNote}

${STRUCTURE}

${CRAFT}

${SAFETY}

${STORY_FORMAT}`;
}

export function writeUserPrompt({ material, dials, plan, critiques = [] }) {
  const planText = plan ? `\n\n[기획안]\n${JSON.stringify(plan, null, 2)}` : "";
  const critiqueText = critiques.length
    ? `\n\n[앞서 만든 꿈에 대한 아이의 반박 — 반영해서 아이가 납득할 수 있게 다시 쓸 것]\n${critiques.map((c, i) => `${i + 1}. ${c}`).join("\n")}`
    : "";
  return `${materialText(material)}\n\n${dialsText(dials)}${planText}${critiqueText}\n\n악몽을 써서 JSON으로 출력하라.`;
}

// ─────────────────────────────────────────────────────────────
// 3) critic → revise
// ─────────────────────────────────────────────────────────────
export function criticSystemPrompt() {
  return `너는 어린이 책 편집자다. 초등 5~6학년용 악몽 이야기 초고를 읽고, 작가에게 줄 구체적인 수정 지시를 쓴다.

볼 것:
- 아이 재료(말·물건·사람)가 진짜로 살아 있나, 아니면 장식으로만 붙었나
- wish 장면이 진짜 부러운가 (안 부러우면 대가도 안 아프다)
- cost가 추상어가 아니라 장면인가
- 리프레인이 세 번 나오고, 뜻이 바뀌는가
- climax가 "AI가 대신할 수 없는 순간"인가
- 훈계·설명·진부한 표현이 있나
- 5학년이 읽기에 어렵거나 긴 문장
- 안전 기준 위반

JSON만 출력:
{ "notes": ["'어느 장면'의 '무엇'을 '어떻게' 바꿔라 — 형식의 구체적 지시 3~6개"], "keep": ["절대 바꾸지 말아야 할 좋은 부분 1~2개"] }`;
}

export function criticUserPrompt({ material, draft }) {
  return `${materialText(material)}\n\n[초고]\n${JSON.stringify(draft, null, 2)}\n\n수정 지시를 JSON으로 출력하라.`;
}

export function reviseUserPrompt({ material, dials, plan, draft, critique }) {
  return `${writeUserPrompt({ material, dials, plan })}

[네가 쓴 초고]
${JSON.stringify(draft, null, 2)}

[편집자 메모]
고칠 것:
${critique.notes.map((n, i) => `${i + 1}. ${n}`).join("\n")}
지킬 것:
${(critique.keep || []).map((n) => `- ${n}`).join("\n")}

메모를 반영해 완성본을 같은 JSON 형식으로 다시 출력하라.`;
}
